#!/usr/bin/env python3
"""Step (b): fetch timestamped transcripts for videos not in cache/transcripts/, with a fallback chain per video:
  1. Apify actor (the original method; needs env APIFY_TOKEN, spend-capped by settings.apify_max_charge_usd_per_run)
  2. youtube-transcript-api (YouTube captions incl. auto-generated, English)
  3. yt-dlp auto-captions (json3)
  4. description chapters ("12:34 Topic" lines) as coarse segments, marked source=description
Each fallback step is retried with backoff. Every cached file records "source". Secrets are never logged.
Usage: 02_transcripts.py [--skip apify,ytapi,ytdlp]"""
import sys, os, json, time, re, random, argparse, subprocess, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
from common import *
ap = argparse.ArgumentParser(); ap.add_argument("--skip", default=""); a = ap.parse_args()
SKIP = set(filter(None, a.skip.split(",")))
run = current_run(); vids = load(f"runs/{run}/videos.json")
TOK = os.environ.get("APIFY_TOKEN")
PAUSE = float(os.environ.get("TRANSCRIPT_PAUSE_S", "2"))
os.makedirs(p("cache/transcripts"), exist_ok=True)
def have(i): return os.path.exists(p("cache/transcripts", i + ".json"))
todo = [v for v in vids if not have(v["id"])]
report = load(f"runs/{run}/transcripts_report.json", {"fetched": [], "failed": {}, "cost_usd": 0.0, "apify_runs": [], "by_source": {}})
report.setdefault("by_source", {})
def put(v, source, segs, lang="en", auto=None, dur=None):
    save(f"cache/transcripts/{v['id']}.json", {"video_id": v["id"], "language": lang, "auto": auto, "duration_s": dur, "source": source,
                                               "segments": [{"start": float(s["start"]), "text": s["text"]} for s in segs if s["text"].strip()]})
    report["fetched"].append(v["id"]); report["failed"].pop(v["id"], None)
    report["by_source"][source] = report["by_source"].get(source, 0) + 1
def retry(fn, tries=3, base=3.0):
    last = None
    for n in range(tries):
        try: return fn()
        except Exception as e:
            last = e
            s = (type(e).__name__ + str(e)).lower()
            if "requestblocked" in s or "not a bot" in s or "disabled" in s or "notranscript" in s or "no transcript" in s or "unavailable" in s: break
            if n < tries - 1: time.sleep(base * 2 ** n + random.random())
    raise last

# 1. Apify (batch)
if todo and TOK and "apify" not in SKIP:
    def api(method, path, body=None):
        return json.loads(fetch("https://api.apify.com/v2" + path, method=method, data=json.dumps(body).encode() if body is not None else None,
                                headers={"Authorization": "Bearer " + TOK, "Content-Type": "application/json"}, timeout=120, secret=True))
    try:
        cap = SETTINGS["apify_max_charge_usd_per_run"]
        log(f"apify: {len(todo)} transcripts, est ${len(todo) * SETTINGS['apify_price_per_transcript_usd']:.3f}, cap ${cap}")
        r = api("POST", f"/acts/{SETTINGS['apify_actor']}/runs?maxTotalChargeUsd={cap}",
                {"videos": [v["url"] for v in todo], "language": "en", "includeTimestamps": True})["data"]
        rid = r["id"]; t0 = time.time()
        while r["status"] in ("READY", "RUNNING") and time.time() - t0 < 1800:
            r = api("GET", f"/actor-runs/{rid}?waitForFinish=60")["data"]; log("apify", r["status"])
        byid = {v["id"]: v for v in todo}
        for it in api("GET", f"/datasets/{r['defaultDatasetId']}/items?clean=1"):
            vid = it.get("videoId")
            if vid in byid and it.get("status") == "ok" and it.get("segments"):
                put(byid[vid], "apify", it["segments"], it.get("transcriptLanguage"), it.get("isAutoGenerated"), it.get("durationSeconds"))
            elif vid: report["failed"][vid] = f"apify:{it.get('status')}"
        report["cost_usd"] += float(r.get("usageTotalUsd") or 0)
        report["apify_runs"].append({"id": rid, "status": r["status"], "usd": r.get("usageTotalUsd")})
    except Exception as e: log("apify step failed:", redact(e), "-> per-video fallbacks")
elif todo and not TOK: log("APIFY_TOKEN not set -> using free fallbacks only")

# 2-4. per-video fallbacks
def ytapi(v):
    from youtube_transcript_api import YouTubeTranscriptApi
    tr = YouTubeTranscriptApi().fetch(v["id"], languages=["en", "en-US", "en-GB"])
    return [{"start": s.start, "text": s.text} for s in tr], getattr(tr, "is_generated", None)
def ytdlp(v):
    with tempfile.TemporaryDirectory() as d:
        subprocess.run([sys.executable, "-m", "yt_dlp", "--skip-download", "--write-auto-subs", "--write-subs", "--sub-langs", "en.*,en", "--sub-format", "json3",
                        "-o", os.path.join(d, "%(id)s.%(ext)s"), "--quiet", "--no-warnings", v["url"]], check=True, timeout=180)
        fs = sorted(f for f in os.listdir(d) if f.endswith(".json3"))
        if not fs: raise RuntimeError("no transcript from yt-dlp")
        ev = json.load(open(os.path.join(d, fs[0]))).get("events", [])
        segs = [{"start": e.get("tStartMs", 0) / 1000, "text": "".join(x.get("utf8", "") for x in e.get("segs", [])).replace("\n", " ")} for e in ev if e.get("segs")]
        if not segs: raise RuntimeError("no transcript (empty json3)")
        return segs
CH = re.compile(r"^\s*\(?((?:\d{1,2}:)?\d{1,2}:\d{2})\)?\s*[-–—:|]?\s*(.+)$")
def chapters(v):
    segs = []
    for line in (v.get("desc") or "").splitlines():
        m = CH.match(line)
        if m:
            parts = [int(x) for x in m.group(1).split(":")]; t = sum(x * 60 ** i for i, x in enumerate(reversed(parts)))
            segs.append({"start": t, "text": m.group(2)})
    if len(segs) < 2: raise RuntimeError("no chapters in description")
    return segs
BLOCKED = {"ytapi": 0, "ytdlp": 0}  # after 3 IP-block errors in a row, stop trying that source this run (cloud IPs are often blocked)
def blocked(e): s = type(e).__name__ + str(e); return "RequestBlocked" in s or "IpBlocked" in s or "not a bot" in s or "returned non-zero" in s
for k, v in enumerate([v for v in todo if not have(v["id"])]):
    if k: time.sleep(PAUSE)
    done = False
    if "ytapi" not in SKIP and BLOCKED["ytapi"] < 3:
        try: segs, auto = retry(lambda: ytapi(v)); put(v, "youtube_transcript_api", segs, "en", auto); done = True; BLOCKED["ytapi"] = 0
        except Exception as e:
            BLOCKED["ytapi"] = BLOCKED["ytapi"] + 1 if blocked(e) else 0
            log(v["id"], "ytapi failed:", type(e).__name__, str(e)[:120].replace("\n", " "))
    if not done and "ytdlp" not in SKIP and BLOCKED["ytdlp"] < 3:
        try: put(v, "yt-dlp", retry(lambda: ytdlp(v)), "en", True); done = True; BLOCKED["ytdlp"] = 0
        except Exception as e:
            BLOCKED["ytdlp"] = BLOCKED["ytdlp"] + 1 if blocked(e) else 0
            log(v["id"], "yt-dlp failed:", str(e)[:120])
    if not done:
        try: put(v, "description", chapters(v), None, None); done = True
        except Exception: report["failed"][v["id"]] = "all fallbacks failed (title/description still used as metadata)"
n = sum(have(v["id"]) for v in vids)
report["coverage"] = f"{n}/{len(vids)}"; save(f"runs/{run}/transcripts_report.json", report)
if any(c >= 3 for c in BLOCKED.values()): log("::warning::YouTube blocked free caption sources from this server; set the APIFY_TOKEN secret for full coverage")
log(f"coverage {n}/{len(vids)} by source {report['by_source']}, Apify cost ${report['cost_usd']:.4f}")
